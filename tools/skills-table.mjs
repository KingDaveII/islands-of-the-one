#!/usr/bin/env node
/**
 * Generates packages/shared/data/skills.json: the cumulative XP needed for
 * each skill level from 1 to 200, from GAME DESIGN's curve (M2 Task 3b):
 * the XP to go from level L to L + 1 is round(40 + 12,300 × (1.08^L − 1.08)),
 * so level 2 is at 40 XP. The game reads the table, never the formula
 * (`skillProgress` in packages/shared/src/skills.ts; beyond the table the
 * same formula runs, in `xpToNext`), and packages/shared/test/skills.test.ts
 * recomputes every entry from the formula.
 *
 *   node tools/skills-table.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LEVELS = 200;
const xpToNext = (level) => Math.round(40 + 12300 * (Math.pow(1.08, level) - 1.08));

const levels = [0];
for (let level = 1; level < LEVELS; level++) levels.push(levels[level - 1] + xpToNext(level));

const out = {
  $comment:
    "Generated by tools/skills-table.mjs from GAME DESIGN's curve (docs/design/holding.md): levels[L - 1] is the cumulative XP a skill needs to be level L, from 1 to 200; the XP from level L to L + 1 is round(40 + 12,300 x (1.08^L - 1.08)). Skills have no level cap: past the table the same formula runs in code. Never edit by hand; run the script.",
  levels,
};
writeFileSync(join(ROOT, 'packages/shared/data/skills.json'), `${JSON.stringify(out, null, 2)}\n`);
console.log(`skills.json: ${levels.length} levels, level 2 at ${levels[1]}, level 10 at ${levels[9]}, level 20 at ${levels[19]}, level 200 at ${levels[199]}`);
